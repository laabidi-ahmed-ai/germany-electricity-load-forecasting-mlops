"""Alembic migrations and the schema-version check in ``db.init_db`` (temp SQLite files).

The live database shares Postgres with MLflow, which keeps its own ``alembic_version``
and tables there - several tests reproduce that to prove ours never touch them. A
Postgres run is opt-in: set ``TEST_POSTGRES_URL`` to an empty throwaway database.
"""

