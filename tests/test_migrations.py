"""Alembic migrations and the schema-version check in ``db.init_db`` (temp SQLite files).

The live database shares Postgres with MLflow, which keeps its own ``alembic_version``
and tables there - several tests reproduce that to prove ours never touch them. A
Postgres run is opt-in: set ``TEST_POSTGRES_URL`` to an empty throwaway database.
"""

from __future__ import annotations

import configparser
import os
import subprocess
import sys
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.migration import MigrationContext
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import inspect, text
from sqlalchemy.engine import Engine

from config.settings import PROJECT_ROOT
from src.data import db

MIGRATIONS = PROJECT_ROOT / "src" / "data" / "migrations"
MLFLOW_REVISION = "mlflow_rev_1"


def alembic_config(url: str) -> Config:
    """The scripts of ``alembic.ini`` without its file, so logging is left alone in-process."""
    cfg = Config()
    cfg.set_main_option("script_location", str(MIGRATIONS))
    cfg.set_main_option("sqlalchemy.url", url.replace("%", "%%"))  # ini-style interpolation
    return cfg


def recorded_revision(engine: Engine) -> str | None:
    with engine.connect() as conn:
        opts = {"version_table": db.SCHEMA_VERSION_TABLE}
        return MigrationContext.configure(conn, opts=opts).get_current_revision()


def add_mlflow_tables(engine: Engine) -> None:
    """What MLflow leaves in a database it tracks into: its version table and its tables."""
    with engine.begin() as conn:
        conn.execute(text("CREATE TABLE alembic_version (version_num VARCHAR(32) PRIMARY KEY)"))
        conn.execute(text(f"INSERT INTO alembic_version VALUES ('{MLFLOW_REVISION}')"))
        conn.execute(text("CREATE TABLE experiments (experiment_id INTEGER PRIMARY KEY)"))
        conn.execute(text("INSERT INTO experiments VALUES (0)"))


def assert_mlflow_untouched(engine: Engine) -> None:
    with engine.connect() as conn:
        assert conn.execute(text("SELECT version_num FROM alembic_version")).scalars().all() == [
            MLFLOW_REVISION
        ]
        assert conn.execute(text("SELECT count(*) FROM experiments")).scalar_one() == 1


def set_recorded_revisions(engine: Engine, *revisions: str) -> None:
    with engine.begin() as conn:
        conn.execute(text(f"DELETE FROM {db.SCHEMA_VERSION_TABLE}"))
        for rev in revisions:
            conn.execute(text(f"INSERT INTO {db.SCHEMA_VERSION_TABLE} VALUES ('{rev}')"))


@pytest.fixture
def url(tmp_path: Path) -> str:
    return f"sqlite:///{(tmp_path / 'app.db').as_posix()}"


@pytest.fixture
def blank(url: str) -> Engine:
    """An engine on a database file that does not exist yet."""
    return db.get_engine(url)


# --- The scripts ---
def test_schema_revisions_match_the_migration_scripts() -> None:
    script = ScriptDirectory.from_config(alembic_config("sqlite://"))
    history = [rev.revision for rev in script.walk_revisions()][::-1]  # oldest first
    assert tuple(history) == db.SCHEMA_REVISIONS
    assert script.get_heads() == [db.SCHEMA_REVISION]


def test_alembic_ini_runs_these_scripts_on_our_version_table() -> None:
    ini = configparser.ConfigParser(defaults={"here": PROJECT_ROOT.as_posix()})
    ini.read(PROJECT_ROOT / "alembic.ini", encoding="utf-8")
    assert Path(ini["alembic"]["script_location"]).resolve() == MIGRATIONS.resolve()
    assert "sqlalchemy.url" not in ini["alembic"]  # the URL comes from DATABASE_URL only
    assert db.SCHEMA_VERSION_TABLE != "alembic_version"  # MLflow's


def test_migrations_build_exactly_the_models(url: str, blank: Engine) -> None:
    command.upgrade(alembic_config(url), "head")
    assert recorded_revision(blank) == db.SCHEMA_REVISION
    command.check(alembic_config(url))  # raises if the schema differs from Base.metadata
    db.init_db(blank)  # a migrated database passes the check


def test_check_sees_drift_in_the_application_tables(url: str, blank: Engine) -> None:
    """Not vacuous: filtering out MLflow's tables must not hide ours."""
    db.init_db(blank)
    with blank.begin() as conn:
        conn.execute(text("ALTER TABLE load_actual ADD COLUMN extra INTEGER"))
    with pytest.raises(AutogenerateDiffsDetected, match="load_actual"):
        command.check(alembic_config(url))


# --- init_db ---
def test_init_db_creates_and_stamps_a_fresh_database(url: str, blank: Engine) -> None:
    db.init_db(blank)
    assert set(db.Base.metadata.tables) <= set(inspect(blank).get_table_names())
    assert recorded_revision(blank) == db.SCHEMA_REVISION
    command.check(alembic_config(url))  # create_all builds what the migrations build
    db.init_db(blank)  # at head: a no-op, also the second time
    assert recorded_revision(blank) == db.SCHEMA_REVISION


def test_the_live_database_must_be_stamped_once(url: str, blank: Engine) -> None:
    """Today's live state: our tables from create_all, MLflow's beside them, no version."""
    db.Base.metadata.create_all(blank)
    add_mlflow_tables(blank)
    with pytest.raises(db.SchemaError, match=r"alembic stamp 0001"):
        db.init_db(blank)

    command.stamp(alembic_config(url), "0001")  # the runbook step
    db.init_db(blank)
    assert recorded_revision(blank) == "0001"
    command.check(alembic_config(url))  # MLflow's tables are not reported as extra
    assert_mlflow_untouched(blank)


def test_init_db_refuses_an_older_schema(blank: Engine, monkeypatch) -> None:
    db.init_db(blank)
    monkeypatch.setattr(db, "SCHEMA_REVISIONS", ("0001", "0002"))
    monkeypatch.setattr(db, "SCHEMA_REVISION", "0002")
    with pytest.raises(db.SchemaError, match=r"at revision 0001, this code needs 0002.*upgrade"):
        db.init_db(blank)


@pytest.mark.parametrize("revision", ["0002", "zzz"])
def test_init_db_refuses_an_unknown_or_newer_schema(blank: Engine, revision: str) -> None:
    db.init_db(blank)
    set_recorded_revisions(blank, revision)
    with pytest.raises(db.SchemaError, match=rf"at revision {revision}, which this code does"):
        db.init_db(blank)


def test_init_db_refuses_several_versions(blank: Engine) -> None:
    db.init_db(blank)
    set_recorded_revisions(blank, "0001", "0002")
    with pytest.raises(db.SchemaError, match="several schema versions"):
        db.init_db(blank)


def test_init_db_refuses_tables_with_an_empty_version_table(blank: Engine) -> None:
    db.init_db(blank)
    set_recorded_revisions(blank)
    with pytest.raises(db.SchemaError, match="no schema version"):
        db.init_db(blank)


def test_a_database_with_only_mlflow_tables_counts_as_new(url: str, blank: Engine) -> None:
    add_mlflow_tables(blank)
    db.init_db(blank)
    assert recorded_revision(blank) == db.SCHEMA_REVISION
    command.upgrade(alembic_config(url), "head")
    command.check(alembic_config(url))
    assert_mlflow_untouched(blank)


def test_the_baseline_cannot_be_downgraded(url: str, blank: Engine) -> None:
    db.init_db(blank)
    with pytest.raises(RuntimeError, match="baseline"):
        command.downgrade(alembic_config(url), "base")
    assert set(db.Base.metadata.tables) <= set(inspect(blank).get_table_names())
    assert recorded_revision(blank) == db.SCHEMA_REVISION


# --- The runbook, through the real CLI and alembic.ini ---
def test_runbook_commands_through_the_cli(url: str, blank: Engine) -> None:
    db.Base.metadata.create_all(blank)  # an existing database that predates migrations
    add_mlflow_tables(blank)

    def alembic(*args: str) -> str:
        out = subprocess.run(
            [sys.executable, "-m", "alembic", *args],
            cwd=PROJECT_ROOT,
            capture_output=True,
            text=True,
            env={**os.environ, "DATABASE_URL": url},
            check=True,
        )
        return out.stdout + out.stderr

    assert "0001" not in alembic("current")
    alembic("stamp", "0001")
    assert "0001 (head)" in alembic("current")
    assert "No new upgrade operations detected" in alembic("check")
    db.init_db(blank)
    assert_mlflow_untouched(blank)


# --- Postgres (opt-in) ---
POSTGRES_URL = os.environ.get("TEST_POSTGRES_URL")


def drop_application_schema(engine: Engine) -> None:
    db.Base.metadata.drop_all(engine)
    with engine.begin() as conn:
        conn.execute(text(f"DROP TABLE IF EXISTS {db.SCHEMA_VERSION_TABLE}"))


@pytest.mark.integration
@pytest.mark.skipif(not POSTGRES_URL, reason="TEST_POSTGRES_URL (an empty database) is not set")
def test_migrations_and_init_db_on_postgres() -> None:
    engine = db.get_engine(POSTGRES_URL)
    ours = set(db.Base.metadata.tables) | {db.SCHEMA_VERSION_TABLE}
    if present := ours & set(inspect(engine).get_table_names()):
        pytest.skip(f"TEST_POSTGRES_URL already has {sorted(present)} - use an empty database")
    cfg = alembic_config(POSTGRES_URL)
    try:
        command.upgrade(cfg, "head")
        command.check(cfg)
        db.init_db(engine)  # migrated: passes

        drop_application_schema(engine)
        db.init_db(engine)  # fresh: create + stamp
        assert recorded_revision(engine) == db.SCHEMA_REVISION
        command.check(cfg)

        with engine.begin() as conn:
            conn.execute(text(f"DROP TABLE {db.SCHEMA_VERSION_TABLE}"))
        with pytest.raises(db.SchemaError, match="alembic stamp 0001"):
            db.init_db(engine)
    finally:
        drop_application_schema(engine)
