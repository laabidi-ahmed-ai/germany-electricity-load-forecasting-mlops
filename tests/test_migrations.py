# --- The runbook, through the real CLI and alembic.ini ---
def test_runbook_commands_through_the_cli(url: str, blank: Engine) -> None:
    db.Base.metadata.create_all(blank)  # an existing database that predates migrations
    add_time_indexes(blank)
    add_mlflow_tables(blank)

    def alembic(*args: str) -> str:
        out = subprocess.run(
            [sys.executable, "-m", "alembic", *args],
            cwd=PROJECT_ROOT,
            capture_output=True,
            text=True,
            env={**os.environ, "DATABASE_URL": url},
            check=True,
        )
        return out.stdout + out.stderr

    assert "0001" not in alembic("current")
    alembic("stamp", "0001")
    assert "0001" in alembic("current")
    alembic("upgrade", "head")
    assert "0002 (head)" in alembic("current")
    assert "No new upgrade operations detected" in alembic("check")
    db.init_db(blank)
    assert_mlflow_untouched(blank)


# --- Postgres (opt-in) ---
POSTGRES_URL = os.environ.get("TEST_POSTGRES_URL")
requires_postgres = pytest.mark.skipif(
    not POSTGRES_URL, reason="TEST_POSTGRES_URL (an empty database) is not set"
)
READER_ROLE = "migration_test_reader"


def drop_application_schema(engine: Engine) -> None:
    db.Base.metadata.drop_all(engine)
    with engine.begin() as conn:
        for table in TIME_SERIES_TABLES:  # an interrupted conversion's copies
            conn.execute(text(f"DROP TABLE IF EXISTS {table}__plain"))
        conn.execute(text(f"DROP TABLE IF EXISTS {db.SCHEMA_VERSION_TABLE}"))


@pytest.fixture
def postgres() -> Iterator[Engine]:
    """An engine on ``TEST_POSTGRES_URL``, refused unless it has none of our tables.

    The tests drop the application's tables when they finish, so a database that already has
    any of them - production, a rehearsal branch - must fail loudly, never be skipped into.
    """
    assert POSTGRES_URL
    engine = db.get_engine(POSTGRES_URL)
    ours = set(db.Base.metadata.tables) | {db.SCHEMA_VERSION_TABLE}
    if present := ours & set(inspect(engine).get_table_names()):
        engine.dispose()
        pytest.fail(
            f"TEST_POSTGRES_URL already has {sorted(present)}. These tests drop the "
            "application's tables: point TEST_POSTGRES_URL at an empty throwaway database, "
            "never at production or a rehearsal branch.",
            pytrace=False,
        )
    try:
        yield engine
    finally:
        drop_application_schema(engine)
        engine.dispose()


def postgres_indexes(engine: Engine, table: str) -> set[str]:
    with engine.connect() as conn:
        return set(
            conn.execute(
                text("SELECT indexname FROM pg_indexes WHERE tablename = :t"), {"t": table}
            ).scalars()
        )


@pytest.mark.integration
@requires_postgres
def test_migrations_and_init_db_on_postgres(postgres: Engine) -> None:
    engine = postgres
    cfg = alembic_config(POSTGRES_URL or "")
    command.upgrade(cfg, "head")
    command.check(cfg)
    db.init_db(engine)  # migrated: passes

    command.downgrade(cfg, "0001")  # without hypertables, 0002 is only its index step
    for table in TIME_SERIES_TABLES:
        assert postgres_indexes(engine, table) == {f"{table}_pkey", f"{table}_timestamp_utc_idx"}
    command.upgrade(cfg, "head")
    command.check(cfg)
    for table in TIME_SERIES_TABLES:
        assert postgres_indexes(engine, table) == {f"{table}_pkey"}

    drop_application_schema(engine)
    db.init_db(engine)  # fresh: create + stamp
    assert recorded_revision(engine) == db.SCHEMA_REVISION
    command.check(cfg)

    with engine.begin() as conn:
        conn.execute(text(f"DROP TABLE {db.SCHEMA_VERSION_TABLE}"))
    with pytest.raises(db.SchemaError, match="alembic stamp 0001"):
        db.init_db(engine)


def seed_time_series(engine: Engine) -> None:
    """Five days of rows in every time-series table: five chunks each at one day per chunk."""
    hours = pd.date_range("2026-10-01", periods=5 * 24, freq="h", tz="UTC")
    issued = pd.Timestamp("2026-09-30 06:00", tz="UTC")
    db.upsert_rows(
        engine,
        db.LoadActual,
        [
            {"timestamp_utc": ts, "source": "smard", "load_mw": 50_000.0 + i}
            for i, ts in enumerate(hours)
        ],
    )
    db.upsert_rows(
        engine,
        db.LoadForecastOfficial,
        [
            {"timestamp_utc": ts, "source": "smard", "forecast_mw": 51_000.0 + i}
            for i, ts in enumerate(hours)
        ],
    )
    db.upsert_rows(
        engine,
        db.WeatherHourly,
        [
            {
                "timestamp_utc": ts,
                "city": city,
                "source": "archive",
                "temperature_2m": 10.0 + i / 10,
                "wind_speed_10m": None,  # NULLs survive the copy
                "shortwave_radiation": 0.0,
                "cloud_cover": 50.0,
                "relative_humidity_2m": 80.0,
            }
            for i, ts in enumerate(hours)
            for city in ("berlin", "munich")
        ],
    )
    db.upsert_rows(
        engine,
        db.LoadForecastModel,
        [
            {
                "timestamp_utc": ts,
                "model_version": "3",
                "model_name": "load-forecaster",
                "forecast_mw": 52_000.0 + i,
                "issued_at": issued,
            }
            for i, ts in enumerate(hours)
        ],
    )


def snapshot(engine: Engine) -> dict[str, list[tuple]]:
    with engine.connect() as conn:
        return {
            table: [
                tuple(row) for row in conn.execute(text(f"SELECT * FROM {table} ORDER BY 1, 2"))
            ]
            for table in TIME_SERIES_TABLES
        }


@pytest.mark.integration
@requires_postgres
@pytest.mark.parametrize("per_table", [False, True], ids=["one-transaction", "per-table"])
def test_0002_converts_hypertables_on_postgres(postgres: Engine, per_table: bool) -> None:
    """Production at 0001, rebuilt with small chunks: four hypertables with grants and rows."""
    engine = postgres
    with engine.connect() as conn:
        available = conn.execute(
            text("SELECT 1 FROM pg_available_extensions WHERE name = 'timescaledb'")
        ).first()
        installed = conn.execute(
            text("SELECT 1 FROM pg_extension WHERE extname = 'timescaledb'")
        ).first()
    if not available:
        pytest.skip("TimescaleDB is not available on TEST_POSTGRES_URL")
    module = migration("0002")
    cfg = alembic_config(POSTGRES_URL or "")
    command.upgrade(cfg, "0001")
    try:
        role: str | None = READER_ROLE
        try:
            with engine.begin() as conn:
                conn.execute(text(f"CREATE ROLE {READER_ROLE} NOLOGIN"))
        except DBAPIError:
            role = None  # not allowed to create roles: the PUBLIC grant still covers the copy
        with engine.begin() as conn:
            conn.execute(text("CREATE EXTENSION IF NOT EXISTS timescaledb"))
            for table in TIME_SERIES_TABLES:
                # As in production: create_hypertable on a plain table makes this index itself.
                conn.execute(text(f"DROP INDEX {table}_timestamp_utc_idx"))
                conn.execute(
                    text(
                        "SELECT create_hypertable(CAST(:t AS regclass), 'timestamp_utc', "
                        "chunk_time_interval => interval '1 day', migrate_data => true)"
                    ),
                    {"t": table},
                )
                conn.execute(text(f"GRANT SELECT ON {table} TO PUBLIC"))
                if role:
                    conn.execute(text(f"GRANT SELECT, INSERT ON {table} TO {role}"))
        seed_time_series(engine)
        with engine.connect() as conn:
            assert module.hypertables(conn) == list(TIME_SERIES_TABLES)
            for table in TIME_SERIES_TABLES:
                chunks = conn.execute(
                    text(
                        "SELECT count(*) FROM timescaledb_information.chunks "
                        "WHERE hypertable_name = :t"
                    ),
                    {"t": table},
                ).scalar_one()
                assert chunks >= 5, table
            grants = {table: module.table_grants(conn, table) for table in TIME_SERIES_TABLES}
        for table in TIME_SERIES_TABLES:
            assert f"{table}_timestamp_utc_idx" in postgres_indexes(engine, table)
        rows = snapshot(engine)

        if per_table:
            cfg.cmd_opts = argparse.Namespace(x=["per_table=true"])
        command.upgrade(cfg, "head")

        assert recorded_revision(engine) == "0002"
        assert snapshot(engine) == rows
        with engine.connect() as conn:
            assert module.hypertables(conn) == []
            for table in TIME_SERIES_TABLES:
                assert module.table_grants(conn, table) == grants[table], table
                key = conn.execute(
                    text(
                        "SELECT conname FROM pg_constraint "
                        "WHERE conrelid = CAST(:t AS regclass) AND contype = 'p'"
                    ),
                    {"t": table},
                ).scalar_one()
                assert key == f"{table}_pkey"
        for table in TIME_SERIES_TABLES:
            assert postgres_indexes(engine, table) == {f"{table}_pkey"}
        command.check(cfg)
        db.init_db(engine)

        # Again after a downgrade: nothing is a hypertable any more, only the index step runs.
        command.downgrade(cfg, "0001")
        command.upgrade(cfg, "head")
        assert snapshot(engine) == rows
        command.check(cfg)
    finally:
        drop_application_schema(engine)
        with engine.begin() as conn:
            if role:  # only the role this test created
                conn.execute(text(f"DROP ROLE {role}"))
            if not installed:
                conn.execute(text("DROP EXTENSION IF EXISTS timescaledb"))
