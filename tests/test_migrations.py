from config.settings import PROJECT_ROOT
from src.data import db

MIGRATIONS = PROJECT_ROOT / "src" / "data" / "migrations"
HEAD = db.SCHEMA_REVISION
MLFLOW_REVISION = "mlflow_rev_1"
# Production's hypertables until 0002, each with its ``<table>_timestamp_utc_idx`` at 0001.
TIME_SERIES_TABLES = (
    "load_actual",
    "load_forecast_official",
    "weather_hourly",
    "load_forecast_model",
)
TIME_INDEXES = {f"{table}_timestamp_utc_idx" for table in TIME_SERIES_TABLES}
NEW_IN_0003 = {"load_forecast_official_revision", "load_forecast_model_weather"}
MODEL_NAME = "germany-load-day-ahead"
# ``load_forecast_model`` as it was up to 0002 - the current model has another key and
# ``horizon`` - so databases at an older revision are seeded through this, not the model.
FORECASTS_0002 = sa.table(
    "load_forecast_model",
    sa.column("timestamp_utc", db.UTCDateTime()),
    sa.column("model_version"),
    sa.column("model_name"),
    sa.column("forecast_mw"),
    sa.column("issued_at", db.UTCDateTime()),
    sa.column("ingested_at", db.UTCDateTime()),
)


def alembic_config(url: str) -> Config:
    """The scripts of ``alembic.ini`` without its file, so logging is left alone in-process."""
    cfg = Config()
    cfg.set_main_option("script_location", str(MIGRATIONS))
    cfg.set_main_option("sqlalchemy.url", url.replace("%", "%%"))  # ini-style interpolation
    return cfg


def migration(revision: str) -> ModuleType:
    """A revision script's module, to test its helpers directly."""
    return ScriptDirectory.from_config(alembic_config("sqlite://")).get_revision(revision).module


def recorded_revision(engine: Engine) -> str | None:
    with engine.connect() as conn:
        opts = {"version_table": db.SCHEMA_VERSION_TABLE}
        return MigrationContext.configure(conn, opts=opts).get_current_revision()


def add_mlflow_tables(engine: Engine) -> None:
    """What MLflow leaves in a database it tracks into: its version table and its tables."""
    with engine.begin() as conn:
        conn.execute(text("CREATE TABLE alembic_version (version_num VARCHAR(32) PRIMARY KEY)"))
        conn.execute(text(f"INSERT INTO alembic_version VALUES ('{MLFLOW_REVISION}')"))
        conn.execute(text("CREATE TABLE experiments (experiment_id INTEGER PRIMARY KEY)"))
        conn.execute(text("INSERT INTO experiments VALUES (0)"))


def build_unversioned_0001(url: str, engine: Engine) -> None:
    """The live database before migrations: 0001's tables - with the time indexes
    ``create_hypertable`` gave production - and no schema version."""
    command.upgrade(alembic_config(url), "0001")
    with engine.begin() as conn:
        conn.execute(text(f"DROP TABLE {db.SCHEMA_VERSION_TABLE}"))


def assert_mlflow_untouched(engine: Engine) -> None:
    with engine.connect() as conn:
        assert conn.execute(text("SELECT version_num FROM alembic_version")).scalars().all() == [
            MLFLOW_REVISION
        ]
        assert conn.execute(text("SELECT count(*) FROM experiments")).scalar_one() == 1


def set_recorded_revisions(engine: Engine, *revisions: str) -> None:
    with engine.begin() as conn:
        conn.execute(text(f"DELETE FROM {db.SCHEMA_VERSION_TABLE}"))
        for rev in revisions:
            conn.execute(text(f"INSERT INTO {db.SCHEMA_VERSION_TABLE} VALUES ('{rev}')"))


def explicit_indexes(engine: Engine) -> set[str]:
    """SQLite indexes created by name (primary keys' automatic indexes have no SQL)."""
    with engine.connect() as conn:
        return set(
            conn.execute(
                text("SELECT name FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL")
            ).scalars()
        )


def insert_forecasts_0002(
    engine: Engine, version: str, hours: pd.DatetimeIndex, issued_at: pd.Timestamp
) -> None:
    """One issue of ``version`` in the shape of revisions 0001 and 0002."""
    with engine.begin() as conn:
        conn.execute(
            sa.insert(FORECASTS_0002),
            [
                {
                    "timestamp_utc": ts,
                    "model_version": version,
                    "model_name": MODEL_NAME,
                    "forecast_mw": 52_000.0 + i,
                    "issued_at": issued_at,
                    "ingested_at": issued_at,
                }
                for i, ts in enumerate(hours)
            ],
        )


def add_export(engine: Engine, version: str, horizon: str) -> None:
    """The ``model_artifacts`` row 0003 reads a version's horizon from."""
    db.store_model_artifact(
        engine,
        name=MODEL_NAME,
        version=version,
        horizon=horizon,
        features="[]",
        bundle=b"zip",
        bundle_sha256="0" * 64,
        bundle_bytes=3,
    )


def primary_key(engine: Engine, name: str) -> list[str]:
    return inspect(engine).get_pk_constraint(name)["constrained_columns"]


def column_names(engine: Engine, name: str) -> set[str]:
    return {c["name"] for c in inspect(engine).get_columns(name)}


def assert_time_indexes(engine: Engine) -> None:
    """Exactly the four ``<table>_timestamp_utc_idx``, on ``timestamp_utc DESC``.

    Checked here directly: SQLite reflects no sort order, so ``alembic check`` would compare
    the index names and columns but not the DESC.
    """
    assert explicit_indexes(engine) == TIME_INDEXES
    with engine.connect() as conn:
        for table in TIME_SERIES_TABLES:
            keys = conn.execute(text(f"PRAGMA index_xinfo('{table}_timestamp_utc_idx')")).all()
            # (seqno, cid, name, desc, coll, key): the key columns, in order
            assert [(row[2], row[3]) for row in keys if row[5]] == [("timestamp_utc", 1)], table


